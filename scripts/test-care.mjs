import assert from 'node:assert/strict';
import {today,addDays,due,tasks,uuid} from '../src/lib/care.ts';
const t=today();const p={id:'p',status:'active',water_days:7,feed_days:30,feed_paused:false,first_water:t,first_feed:t,snooze_water:null,snooze_feed:null,repot_due:null};
const e=(date,kind='water')=>({id:uuid(),plant_id:'p',kind,occurred_on:date});
assert.equal(addDays('2026-03-28',2),'2026-03-30');
assert.equal(addDays('2026-10-24',2),'2026-10-26');
assert.equal(addDays('2028-02-28',1),'2028-02-29');
assert.equal(due(p,[],'water'),t,'No invented care history');
assert.equal(due({...p,snooze_water:addDays(t,2)},[],'water'),addDays(t,2),'Snooze changes only due date');
const events=[e(addDays(t,-2)),e(addDays(t,-9))];
assert.equal(due(p,events,'water'),addDays(t,5),'Backdated event cannot replace latest watering');
assert.equal(due(p,events.slice(1),'water'),addDays(t,-2),'Removing latest event recalculates due');
assert.equal(due(p,events,'feed'),t,'Watering does not imply fertilizer');
assert.equal(tasks([{...p,status:'archived'}],events).length,0);
assert.equal(tasks([{...p,feed_paused:true}],events).length,1);
assert.equal(tasks([p],events).length,2,'One task per type, no accumulated overdue duplicates');
assert.equal(due(p,[e(addDays(t,3)),...events],'water'),addDays(t,5),'Future events cannot reset present schedule');
assert.match(uuid(),/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
console.log('12 care/date checks passed.');
